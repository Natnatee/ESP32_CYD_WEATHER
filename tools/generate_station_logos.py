"""Offline SVG -> 8x supersampled / Lanczos RGB565 logo assets (no board runtime dependency).
Developer prerequisites: pip install resvg-py==0.2.5 Pillow
Run: python tools/generate_station_logos.py [--check]
No downloads during generation/build/runtime. Sources and trademark attribution: assets/logos/README.md.
"""
from pathlib import Path
import argparse
import hashlib
import io
import re
import xml.etree.ElementTree as ET
from PIL import Image, ImageDraw
import resvg_py

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ROOT / "assets/logos"
WIDTH, HEIGHT, SCALE = 60, 56, 8
HEADER = ROOT / "src/station_logos.h"
OUTPUT = ROOT / "src/station_logos.cpp"


def safe_svg(name):
    text = (SOURCES / name).read_text(encoding="utf-8")
    assert not any(tag in text.lower() for tag in ("<script", "<image", "<foreignobject", "<!doctype", "<text")), name
    for url in re.findall(r"url\(([^)]+)\)", text):
        assert url.strip("'\" ").startswith("#"), (name, url)
    tree = ET.fromstring(text)
    for element in tree.iter():
        for key, value in element.attrib.items():
            if key.split("}")[-1] == "href":
                assert value.startswith("#"), (name, value)
    return text


def render(name, zoom=1, width=None):
    data = resvg_py.svg_to_bytes(svg_string=safe_svg(name), zoom=zoom, width=width, skip_system_fonts=True)
    return Image.open(io.BytesIO(data)).convert("RGBA")


def images():
    result = []
    for name in ("ptt_reproduced.svg", "pt_reproduced.svg"):
        high = render(name, width=WIDTH * SCALE)
        assert high.size == (WIDTH * SCALE, HEIGHT * SCALE)
        result.append(high.convert("RGB").resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS))
    # Preserve official emblem paths/gradients and lettering, recompose instead of shrinking
    # the very wide official horizontal lockup into unreadable text.
    original = render("bangchak_official.svg", 4)
    high = Image.new("RGB", (WIDTH * SCALE, HEIGHT * SCALE), "white")
    draw = ImageDraw.Draw(high)
    draw.rounded_rectangle((4, 4, WIDTH * SCALE - 5, HEIGHT * SCALE - 5), radius=55,
                           fill="white", outline="#249A47", width=10)
    mark = original.crop((0, 0, 260 * 4, original.height))
    mark.thumbnail((39 * SCALE, 39 * SCALE), Image.Resampling.LANCZOS)
    high.paste(mark, ((WIDTH * SCALE - mark.width) // 2, 3 * SCALE), mark)
    word = original.crop((286 * 4, 70 * 4, original.width, original.height))
    word.thumbnail((54 * SCALE, 12 * SCALE), Image.Resampling.LANCZOS)
    high.paste(word, ((WIDTH * SCALE - word.width) // 2, 43 * SCALE), word)
    result.append(high.resize((WIDTH, HEIGHT), Image.Resampling.LANCZOS))
    return result


def rgb565(image):
    data = bytearray()
    for r, g, b in image.getdata():
        pixel = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        data.extend((pixel & 255, pixel >> 8))
    return bytes(data)


def generated(images):
    header = '''#pragma once
#include <lvgl.h>
namespace station_logos {
constexpr int WIDTH = 60, HEIGHT = 56;
extern const lv_img_dsc_t images[3];
} // namespace station_logos
'''
    lines = ['// Generated by tools/generate_station_logos.py. RGB565 LE, antialiased, flash-only.',
             '// PTT/PT: reproductions. Bangchak: official SVG cropped/recomposed for display.',
             '// Trademarks remain their owners\' property; see assets/logos/README.md.',
             '#include "station_logos.h"',
             'static_assert(LV_COLOR_DEPTH == 16 && LV_COLOR_16_SWAP == 0, "Logo format is RGB565 LE");',
             'namespace station_logos {', 'namespace {']
    for name, image in zip(("PTT", "PT", "BANGCHAK"), images):
        data = rgb565(image)
        lines.append(f'// {name}: {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()}')
        lines.append(f'LV_ATTRIBUTE_MEM_ALIGN const uint8_t {name}_PIXELS[] = {{')
        for start in range(0, len(data), 24):
            lines.append('    ' + ','.join(f'0x{value:02X}' for value in data[start:start + 24]) + ',')
        lines.append('};')
    lines.extend(['} // namespace', 'const lv_img_dsc_t images[3] = {'])
    for name in ("PTT", "PT", "BANGCHAK"):
        lines.append(f'    {{{{LV_IMG_CF_TRUE_COLOR, 0, 0, WIDTH, HEIGHT}}, {WIDTH * HEIGHT * 2}, {name}_PIXELS}},')
    lines.extend(['};', '} // namespace station_logos', ''])
    return header, '\n'.join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if checked-in assets differ; never overwrite in check mode")
    args = parser.parse_args()
    rendered = images()
    texts = generated(rendered)
    for path, text in zip((HEADER, OUTPUT), texts):
        if args.check:
            assert path.read_text(encoding="utf-8") == text, f"Regenerate {path.name}"
        else:
            path.write_text(text, encoding="utf-8")
    if not args.check:
        previews = ROOT / ".pio/host_ui"
        previews.mkdir(parents=True, exist_ok=True)
        for name, image in zip(("ptt", "pt", "bangchak"), rendered):
            image.save(previews / f"logo-{name}-60x56.png")
    print(f"PASS: 3 antialiased {WIDTH}x{HEIGHT} RGB565 logos, {3 * WIDTH * HEIGHT * 2} bytes in flash (no runtime rasterization).")
